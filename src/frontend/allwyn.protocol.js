/**
 * The gameserver websocket protocol, written down.
 *
 * bridge.html handles messages with a chain of `data.message == "..."` string
 * comparisons and reads fields straight off the parsed JSON, so a renamed or
 * missing field fails somewhere deep in a render call. Here every message the
 * server can send is declared with its required fields, and anything
 * unexpected is reported once, by name, at the point it arrives.
 *
 * Server messages (src/human.py, src/game.py) and client replies
 * (the ws.send calls in bridge.html) are both listed, so this file is the
 * place to look when the protocol changes.
 */

/** Inbound: message name -> fields that must be present. */
export const INBOUND = {
    deal_start:     ['dealer', 'vuln', 'hand', 'board_no'],
    bid_made:       ['auction'],
    get_bid_input:  ['auction'],
    hint:           ['bids'],
    alert:          ['alert'],
    auction_end:    ['auction', 'declarer', 'strain'],
    show_dummy:     ['player', 'dummy'],
    card_played:    ['card', 'player'],
    get_card_input: [],
    claim_rejected: [],
    trick_confirm:  [],
    deal_end:       ['pbn', 'dict'],
};

/** Outbound replies. The server matches on these exact strings. */
export const OUTBOUND = {
    bid: (call) => call,                    // "1S", "PASS", "X", "XX"
    hint: () => 'Hint',
    toggleAlert: () => 'Alert',
    card: (symbol) => symbol,               // "SA"
    claim: (tricks) => `Claim ${tricks}`,
    concede: () => 'Conceed',               // server's spelling
    confirmTrick: () => 'y',
};

export class ProtocolError extends Error {
    constructor(message, raw) {
        super(message);
        this.name = 'ProtocolError';
        this.raw = raw;
    }
}

/**
 * Parse a raw websocket payload into a validated message.
 * Throws ProtocolError rather than letting a bad shape surface later as an
 * "undefined is not an object" in rendering.
 */
export function parseMessage(rawData) {
    let data;
    try {
        data = JSON.parse(rawData);
    } catch (cause) {
        throw new ProtocolError('Server sent a payload that is not JSON', rawData);
    }

    const name = data?.message;
    if (!name) throw new ProtocolError('Server message has no "message" field', data);

    const required = INBOUND[name];
    if (!required) throw new ProtocolError(`Unknown server message "${name}"`, data);

    const missing = required.filter((field) => data[field] === undefined);
    if (missing.length > 0) {
        throw new ProtocolError(`Message "${name}" is missing: ${missing.join(', ')}`, data);
    }

    return data;
}

/**
 * Read the seat/behaviour flags out of the page URL.
 * Same parameter names bridge.html uses, so links generated by appserver.py
 * and the ones in viz.html work against either UI unchanged.
 */
export function readOptions(search = window.location.search) {
    const p = new URLSearchParams(search);
    const seats = {
        north: p.get('N'),
        east: p.get('E'),
        south: p.get('S'),
        west: p.get('W'),
    };
    return {
        seats,
        humanSeats: [seats.north, seats.east, seats.south, seats.west].map(Boolean),
        noHuman: !seats.north && !seats.east && !seats.south && !seats.west,
        dealId: p.get('deal'),
        boardNo: p.get('board_no'),
        name: p.get('name'),
        server: p.get('server') ?? '3',
        timeoutSeconds: Number(p.get('T')) || 0,
        humanDeclares: p.get('H'),
        autocomplete: p.get('A'),
        continuous: p.get('C'),
        rotate: p.get('R'),
        allVisible: p.get('V') === 'x',
        playOnly: p.get('P'),
        matchpoint: p.get('M'),
        play: p.get('play'),
    };
}

/** Build the query string the gameserver expects on the websocket URL. */
export function buildQueryString(options, search = window.location.search) {
    const p = new URLSearchParams(search);
    const parts = [];
    for (const key of ['N', 'E', 'S', 'W', 'H', 'A', 'C', 'R', 'V', 'M']) {
        if (p.get(key)) parts.push(`${key}=x`);
    }
    for (const key of ['name', 'T', 'P']) {
        if (p.get(key)) parts.push(`${key}=${p.get(key)}`);
    }
    if (options.play) parts.push('play=True');

    const head = [];
    if (options.dealId) head.push(`deal=${options.dealId}`, `board_no=${options.boardNo}`);
    else if (options.boardNo) head.push(`board_no=${options.boardNo}`);

    return '?' + [...head, ...parts].join('&');
}
